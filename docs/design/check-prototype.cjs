// Visual-prototype checks only. Does not exercise Tauri, libmpv or the server.
const { chromium } = require(process.env.CHILL_PREVIEW_NODE_MODULES + '/playwright');
const path = require('node:path');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const { pathToFileURL } = require('node:url');
(async () => {
  const output = process.argv[2];
  assert(output, 'Pass a screenshot output directory');
  await fs.mkdir(output, { recursive: true });
  const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--disable-background-networking', '--no-first-run'] });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('http://**/*', route => route.abort());
    await page.route('https://**/*', route => route.abort());
    await page.goto(pathToFileURL(path.join(__dirname, 'prototype.html')).href);
    await page.screenshot({ path: path.join(output, 'catalogue.png'), fullPage: true });
    assert.equal(await page.locator('.media-card').count(), 8);
    assert.equal(await page.locator('.brand').innerText(), '', 'Branding has no text beside the logo');
    assert.equal((await page.locator('.brand img').boundingBox()).width, 96, 'Desktop logo is larger');
    for (const id of ['refresh', 'enrich', 'admin-ai']) assert.equal(await page.locator('#' + id).isVisible(), false, 'Admin action not visible in catalogue: ' + id);
    assert.equal(await page.locator('#catalogue-ai').count(), 0);
    assert.equal(await page.locator('#side-ai').count(), 0);
    await page.getByRole('button', { name: 'Voir la fiche de Dune', exact: true }).click();
    const bounds = await page.locator('#detail').boundingBox();
    assert(bounds.width > 1100, 'Detail fiche should be wide on desktop');
    assert.equal(await page.locator('#detail-unavailable').isVisible(), false);
    assert.equal(await page.locator('#detail .detail-meta').getByText('Disponible', { exact: true }).count(), 0);
    await page.screenshot({ path: path.join(output, 'fiche.png') });
    await page.locator('#detail-play').click();
    await page.mouse.move(650, 400);
    assert.equal(await page.locator('#play-pause').getAttribute('aria-label'), 'Mettre en pause');
    await page.screenshot({ path: path.join(output, 'lecteur.png') });
    await page.waitForFunction(() => document.getElementById('player').classList.contains('idle'), { timeout: 5000 });
    await page.mouse.move(670, 420);
    assert.equal(await page.locator('#player').evaluate(el => el.classList.contains('idle')), false);
    await page.locator('#play-pause').click();
    await page.locator('#play-pause').evaluate(el => el.blur());
    await page.waitForTimeout(2800);
    assert.equal(await page.locator('#player').evaluate(el => el.classList.contains('idle')), false, 'Paused controls stay visible');
    await page.locator('#fullscreen').click();
    assert.equal(await page.evaluate(() => document.fullscreenElement?.id), 'player');
    const full = await page.locator('#player').boundingBox();
    const viewport = page.viewportSize();
    assert(full.width >= viewport.width && full.height >= viewport.height);
    await page.locator('#back').click();
    await page.locator('[data-category="serie"]').click();
    assert.equal(await page.locator('.series-stats').innerText(), '2 saisons · 5 épisodes · 3 épisodes non vus');
    await page.getByRole('button', { name: 'Voir la fiche de The Expanse', exact: true }).click();
    await page.screenshot({ path: path.join(output, 'serie-saisons.png') });
    await page.getByRole('button', { name: 'Ouvrir la saison 1', exact: true }).click();
    assert.equal(await page.locator('.episode-row').count(), 3);
    await page.getByRole('button', { name: 'Épisode 2', exact: true }).click();
    assert.equal(await page.locator('#detail-title').innerText(), 'The Expanse — S1E2');
    await page.getByRole('button', { name: 'Revenir à la saison 1', exact: false }).click();
    await page.getByRole('button', { name: 'Toutes les saisons', exact: false }).click();
    await page.getByRole('button', { name: 'Ouvrir la saison 2', exact: true }).click();
    await page.screenshot({ path: path.join(output, 'saison-episodes.png') });
    await page.getByRole('button', { name: 'Épisode 2', exact: true }).click();
    assert.equal(await page.locator('#detail-unavailable').isVisible(), true);
    assert.equal(await page.locator('#detail-play').isDisabled(), true);
    await page.screenshot({ path: path.join(output, 'episode-indisponible.png') });
    await page.locator('#detail-watched').click();
    await page.getByRole('button', { name: 'Revenir à la saison 2', exact: false }).click();
    assert.match(await page.locator('#series-explorer .series-summary').innerText(), /1 épisode non vu/);
    await page.getByRole('button', { name: 'Épisode 2', exact: true }).click();
    await page.locator('#detail-watched').click();
    await page.locator('#close-detail').click();
    await page.locator('[data-category="all"]').click();
    for (const [kind, createName, name] of [['saga', 'Créer une saga', 'Ma saga test'], ['playlist', 'Créer une liste de lecture', 'Ma liste test']]) {
      await page.locator(`[data-collection="${kind}"]`).click();
      await page.getByRole('button', { name: createName, exact: false }).click();
      await page.locator('#collection-name').fill(name);
      await page.screenshot({ path: path.join(output, kind + '-creation.png') });
      await page.locator('#collection-editor label').filter({ hasText: 'Dune', hasNotText: 'deuxième' }).locator('input').check();
      await page.locator('#collection-editor form button.primary').click();
      assert.equal(await page.locator('#page-title').innerText(), name);
      assert.equal(await page.locator('.member-row').count(), 1);
      await page.getByRole('button', { name: 'Ajouter des vidéos', exact: false }).click();
      assert.equal(await page.locator('#collection-editor .video-picker label').filter({ hasText: /^Dune$/ }).count(), 0, 'Existing member hidden');
      await page.locator('#collection-editor .video-picker label').filter({ hasText: 'Interstellar' }).locator('input').check();
      await page.locator('#collection-editor form button.primary').click();
      assert.equal(await page.locator('.member-row').count(), 2);
      assert((await page.locator('.member-row').first().boundingBox()).width > 900, 'Collection members fill the content area');
      await page.screenshot({ path: path.join(output, kind + '-membres.png') });
    }
    await page.locator('#profile').click();
    await page.locator('[data-collection="playlist"]').click();
    assert.equal(await page.getByRole('button', { name: 'Ouvrir Ma liste test', exact: true }).count(), 0, 'Playlist belongs to the active profile');
    await page.locator('[data-collection="saga"]').click();
    assert.equal(await page.getByRole('button', { name: 'Ouvrir Ma saga test', exact: true }).count(), 1, 'Saga is common');
    await page.locator('#profile').click();
    await page.locator('[data-category="all"]').click();
    await page.locator('#side-admin').click();
    for (const id of ['refresh', 'enrich', 'admin-ai']) assert.equal(await page.locator('#' + id).isVisible(), true);
    await page.screenshot({ path: path.join(output, 'administration.png') });
    await page.locator('#refresh').click();
    assert.match(await page.locator('#admin-feedback').innerText(), /aucun scan/);
    await page.locator('#enrich').click();
    assert.equal(await page.locator('[data-section="tmdb"]').isVisible(), true);
    await page.locator('[data-tab="tmdb"]').click();
    await page.screenshot({ path: path.join(output, 'tmdb.png') });
    await page.locator('#tmdb-token').fill('NOT_A_REAL_SECRET_TEST_FIXTURE');
    await page.locator('#tmdb-form button').click();
    assert.equal(await page.locator('#tmdb-token').inputValue(), '');
    assert.equal(await page.evaluate(() => localStorage.length), 0);
    await page.locator('#admin-ai').click();
    await page.locator('#ai-form .primary').click();
    await page.screenshot({ path: path.join(output, 'ia.png') });
    assert.equal(await page.locator('#side-admin').getAttribute('class'), 'nav-link active');
    await page.locator('#side-advice').click();
    await page.locator('#advice-request').fill('Une aventure de science-fiction immersive pour ce soir');
    await page.locator('#advice-form button').click();
    assert.equal(await page.locator('#ai-view').isVisible(), false);
    assert.equal(await page.locator('.advice-result').count(), 3);
    assert.equal(await page.locator('#advice-view .prototype-action').count(), 0, 'Advice has no catalogue mutation action');
    await page.screenshot({ path: path.join(output, 'conseil.png') });
    await page.locator('.advice-result').first().getByRole('button', { name: 'Voir la fiche' }).click();
    assert.equal(await page.locator('#detail-title').innerText(), 'Dune');
    await page.locator('#close-detail').click();
    await page.locator('#advice-watched').selectOption('true');
    assert.equal(await page.locator('#advice-preview').isVisible(), false, 'Filters invalidate old suggestions');
    await page.locator('#advice-type').selectOption('film');
    await page.locator('#advice-form button').click();
    assert.deepEqual(await page.locator('.advice-result h3').allTextContents(), ['Blade Runner 2049', 'Solaris']);
    await page.locator('#advice-type').selectOption('serie');
    await page.locator('#advice-form button').click();
    assert.equal(await page.locator('.advice-result').count(), 0, 'No watched series in fixtures');
    assert.match(await page.locator('#advice-results').innerText(), /Aucune vidéo/);
    await page.locator('#advice-watched').selectOption('false');
    await page.locator('#advice-form button').click();
    assert.deepEqual(await page.locator('.advice-result h3').allTextContents(), ['The Expanse']);
    await page.screenshot({ path: path.join(output, 'conseil-series-non-vues.png') });
    await page.locator('#advice-type').selectOption('film');
    await page.locator('#advice-form button').click();
    assert.deepEqual(await page.locator('.advice-result h3').allTextContents(), ['Dune', 'Interstellar', 'Premier contact']);
    await page.setViewportSize({ width: 390, height: 900 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Advice filters fit narrow viewport');
    await page.screenshot({ path: path.join(output, 'conseil-390.png'), fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.locator('#advice-type').selectOption('');
    await page.locator('#advice-watched').selectOption('');
    await page.locator('#advice-form button').click();
    await page.screenshot({ path: path.join(output, 'conseil.png') });
    await page.locator('[data-category="all"]').click();
    await page.locator('#list-view').click();
    assert((await page.locator('.poster-open').first().boundingBox()).height < 150);
    await page.getByRole('button', { name: 'Affichage en grille', exact: true }).click();
    for (const width of [1180, 760, 390]) {
      await page.setViewportSize({ width, height: 900 });
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
      assert.equal(overflow, false, 'Horizontal overflow at ' + width);
      await page.screenshot({ path: path.join(output, `catalogue-${width}.png`), fullPage: true });
    }
    assert.deepEqual(errors, []);
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.locator('#side-admin').click();
    await page.locator('[data-tab="client"]').click();
    await page.locator('#theme').selectOption('light');
    await page.locator('[data-category="all"]').click();
    await page.screenshot({ path: path.join(output, 'catalogue-clair.png'), fullPage: true });
    console.log('PASS CC-UX-002: advice filters, series counters/seasons/episodes/unavailable, collection creation/addition without duplicates, common sagas/personal lists, prior prototype paths. Native playback and real AI NOT_RUN.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
